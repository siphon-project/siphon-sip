/// One AVP of the tables, with whether it goes out with the M bit.
pub(super) struct PolicyAvp {
    pub(super) definition: AvpDef,
    pub(super) mandatory: bool,
}

const MANDATORY: bool = true;
const NOT_MANDATORY: bool = false;

const fn policy_avp(
    code: u32,
    name: &'static str,
    data_type: AvpType,
    mandatory: bool,
) -> PolicyAvp {
    PolicyAvp {
        definition: AvpDef {
            code,
            vendor_id: VENDOR_3GPP,
            name,
            data_type,
        },
        mandatory,
    }
}

