//! The policy and charging control AVPs: every AVP TS 29.212 (Gx) and TS
//! 29.214 (Rx) define, in their tables 5.3.0.1 (Rel-18), and the 3GPP-*
//! attributes of TS 29.061 their re-used tables take over. All of them are
//! 3GPP vendor-specific (10415).
//!
//! Each entry carries its M bit as the table gives it: `MANDATORY` where M is
//! under "Must", `NOT_MANDATORY` where it is under "Must not" or under no
//! column at all. The tables decide the bit per AVP, so it lives next to the
//! definition rather than in a list of exceptions. The 3GPP-* attributes are V
//! under "Must" and M under "Must not" in TS 29.061 table 9a, and both re-used
//! tables either keep that or say "shall have the 'M' bit cleared".
//!
//! Left out: Max-PLR-DL/UL (TS 29.212) and Desired-Max-Latency/Loss (TS
//! 29.214), which are Float32, a type this dictionary does not encode; and the
//! Gxx, Sd and St AVPs of clauses 5a, 5b and 5c and annex E.

use super::AvpDef;
