/// The entry for `code`, all of them being 3GPP vendor-specific.
pub(super) fn lookup(code: u32) -> Option<&'static PolicyAvp> {
    POLICY_AVPS
        .binary_search_by(|entry| entry.definition.code.cmp(&code))
        .ok()
        .map(|index| &POLICY_AVPS[index])
}
