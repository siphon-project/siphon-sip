//! Sy messages (TS 29.219) written out octet by octet, for the tests that
//! read what a PCRF and an OCS send.
//!
//! None of this comes from the encoder under test. The octets were worked out
//! by hand from the AVP header of RFC 6733 clause 4.1 (code, flags, 24-bit
//! length, vendor, padding to four octets), the ABNF of TS 29.219 clauses 5.6.2
//! to 5.6.7 and the flags of its table 5.3.0.1 (M and V on every AVP but
//! SN-Request-Type, which is V only), and Wireshark's Diameter dissector
//! reads the messages built from them as what the comments say. Each constant
//! is the AVPs after the 20-octet header, as the header's hop-by-hop and
//! end-to-end identifiers belong to the connection that sends them. All of
//! them are in one Sy session, the PCRF's `pcrf.epc...;5;5`.

